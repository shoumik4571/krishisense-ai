import {
  addDoc,
  collection,
  getDocs,
  limit,
  orderBy,
  query,
  serverTimestamp,
} from "firebase/firestore";
import { getDownloadURL, ref, uploadString } from "firebase/storage";
import { ensureAnonymousAuth, getFirebase } from "./firebase";
import type { CropAnalysis, FarmProfile } from "./types";

/** Local-first persistence with optional Firestore/Storage enhancement. */

const FARM_KEY = "krishisense:farm";
const ANALYSES_KEY = "krishisense:analyses";

export function saveFarmLocal(farm: FarmProfile): void {
  try {
    localStorage.setItem(FARM_KEY, JSON.stringify(farm));
  } catch {
    /* storage unavailable — ignore */
  }
}

export function loadFarmLocal(): FarmProfile | null {
  try {
    const raw = localStorage.getItem(FARM_KEY);
    return raw ? (JSON.parse(raw) as FarmProfile) : null;
  } catch {
    return null;
  }
}

export function saveAnalysisLocal(analysis: CropAnalysis): void {
  try {
    const raw = localStorage.getItem(ANALYSES_KEY);
    const list: CropAnalysis[] = raw ? JSON.parse(raw) : [];
    list.unshift(analysis);
    localStorage.setItem(ANALYSES_KEY, JSON.stringify(list.slice(0, 10)));
  } catch {
    /* ignore */
  }
}

export function loadAnalysesLocal(): CropAnalysis[] {
  try {
    const raw = localStorage.getItem(ANALYSES_KEY);
    return raw ? (JSON.parse(raw) as CropAnalysis[]) : [];
  } catch {
    return [];
  }
}

export async function persistFarmRemote(farm: FarmProfile): Promise<string | null> {
  const { db, configured } = getFirebase();
  if (!configured || !db) return null;
  try {
    const uid = await ensureAnonymousAuth();
    const doc = await addDoc(collection(db, "farms"), {
      ...farm,
      userId: uid,
      createdAt: serverTimestamp(),
    });
    return doc.id;
  } catch {
    return null;
  }
}

export async function persistAnalysisRemote(
  analysis: CropAnalysis,
): Promise<string | null> {
  const { db, configured } = getFirebase();
  if (!configured || !db) return null;
  try {
    const uid = await ensureAnonymousAuth();
    const { id, ...rest } = analysis;
    void id; // local id is regenerated by Firestore
    const doc = await addDoc(collection(db, "analyses"), {
      ...rest,
      userId: uid,
      createdAt: serverTimestamp(),
    });
    return doc.id;
  } catch {
    return null;
  }
}

export async function uploadImageRemote(
  farmId: string,
  analysisId: string,
  dataUrl: string,
): Promise<string | null> {
  const { storage, configured } = getFirebase();
  if (!configured || !storage) return null;
  try {
    await ensureAnonymousAuth();
    const path = `crop-images/${farmId}/${analysisId}.jpg`;
    const storageRef = ref(storage, path);
    await uploadString(storageRef, dataUrl, "data_url");
    return await getDownloadURL(storageRef);
  } catch {
    return null;
  }
}

export async function loadRecentAnalysesRemote(): Promise<CropAnalysis[] | null> {
  const { db, configured } = getFirebase();
  if (!configured || !db) return null;
  try {
    const q = query(
      collection(db, "analyses"),
      orderBy("createdAt", "desc"),
      limit(5),
    );
    const snap = await getDocs(q);
    return snap.docs.map((d) => ({ id: d.id, ...(d.data() as object) }) as CropAnalysis);
  } catch {
    return null;
  }
}
